#!/bin/bash

# Немедленно выходить, если команда завершилась с ошибкой
set -e

# --- КОНФИГУРАЦИЯ ---
# Замените на ваши значения
IMAGE_NAME="voron-club-app"
CONTAINER_NAME="voron-club-container"
GIT_BRANCH="club" # или "master"

# --- 1. GIT: Сохранение и выгрузка изменений ---
echo ">>> 1. Сохранение и выгрузка изменений в Git..."

# Проверяем, есть ли вообще изменения для коммита
if [[ -z $(git status --porcelain) ]]; then
    echo ">>> Git: Нет новых изменений для коммита."
else
    echo ">>> Git: Найдены изменения, создаю коммит..."
    # Добавляем все измененные файлы
    git add .
    # Создаем коммит с текущей датой и временем
    git commit -m "Deploy: $(date +'%Y-%m-%d %H:%M:%S')"
fi

# Выгружаем последние коммиты на GitHub (этот шаг теперь выполнится всегда)
git push origin $GIT_BRANCH

echo ">>> Git: Локальные изменения синхронизированы с удаленным репозиторием."

# --- 2. DOCKER: Сборка нового образа ---
echo ">>> 2. Сборка нового Docker-образа..."
docker build -t $IMAGE_NAME .
echo ">>> Docker: Образ '$IMAGE_NAME' успешно собран."

# --- 3. DOCKER: Перезапуск контейнера ---
echo ">>> 3. Перезапуск Docker-контейнера..."

# Останавливаем старый контейнер, если он существует. `|| true` предотвращает ошибку, если контейнера нет.
docker stop $CONTAINER_NAME || true

# Удаляем старый контейнер, если он существует.
docker rm $CONTAINER_NAME || true

echo ">>> Docker: Старый контейнер остановлен и удален."

# Запускаем новый контейнер из нового образа
docker run -d \
  -p 5002:5002 \
  --name $CONTAINER_NAME \
  --restart always \
  $IMAGE_NAME

echo ">>> Docker: Новый контейнер '$CONTAINER_NAME' успешно запущен."

# --- ЗАВЕРШЕНИЕ ---
echo ">>> Развертывание успешно завершено! <<<"
